export const DICT = {
  en,
  'pt-BR': ptBR,
} as const;

export type TKey = keyof typeof en;

export function useT() {
  const { state, setLang } = useStore();
  const lang: Lang = (state.lang ?? 'en') as Lang;

  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>): string => {
      const table = DICT[lang] ?? en;
      let str: string = table[key] ?? en[key] ?? String(key);
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          str = str.replaceAll(`{${k}}`, String(v));
        }
      }
      return str;
    },
    [lang],
  );

  return { t, lang, setLang };
}